create or replace function public.current_profile_id() returns bigint
language sql stable security definer set search_path=public as $$
  select id from public.profiles where auth_user_id = auth.uid() limit 1
$$;

create or replace function public.is_workspace_member(p_workspace_id bigint) returns boolean
language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.workspace_members where workspace_id=p_workspace_id and user_id=auth.uid() and is_active=true)
$$;

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path=public as $$
declare p_id bigint; w_id bigint; w_name text; w_slug text;
begin
  insert into public.profiles(auth_user_id,name,email)
  values(new.id, coalesce(new.raw_user_meta_data->>'name', split_part(new.email,'@',1)), new.email)
  returning id into p_id;
  w_name := coalesce(nullif(new.raw_user_meta_data->>'workspace_name',''), 'My Workspace');
  w_slug := lower(regexp_replace(w_name,'[^a-zA-Z0-9]+','-','g')) || '-' || substr(new.id::text,1,8);
  insert into public.workspaces(name,slug,owner_profile_id) values(w_name,w_slug,p_id) returning id into w_id;
  insert into public.workspace_members(workspace_id,profile_id,user_id,role) values(w_id,p_id,new.id,'owner');
  insert into public.clients(workspace_id,name,colour,icon) values(w_id,'Internal','#64748B','🏠');
  insert into public.channels(workspace_id,name,type,icon,created_by_profile_id) values(w_id,'Team General','team','💬',p_id);
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.record_task_status_change() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if old.status is distinct from new.status then
    insert into public.task_status_histories(task_id,changed_by_profile_id,from_status,to_status)
    values(new.id,public.current_profile_id(),old.status,new.status);
    new.completed_at := case when new.status='done' then now() else null end;
  end if;
  new.updated_at := now();
  return new;
end $$;
create trigger task_status_change before update on public.tasks for each row execute function public.record_task_status_change();

create or replace function public.detect_task_suggestion(p_message_id bigint) returns bigint
language plpgsql security definer set search_path=public as $$
declare m public.messages; mentioned text; assignee bigint; task_title text; suggestion_id bigint;
begin
  select * into m from public.messages where id=p_message_id and public.is_workspace_member(workspace_id);
  if not found then return null; end if;
  mentioned := substring(m.body from '@([A-Za-z0-9_]+)');
  if mentioned is null then return null; end if;
  select p.id into assignee from public.profiles p join public.workspace_members wm on wm.profile_id=p.id
   where wm.workspace_id=m.workspace_id and lower(split_part(p.name,' ',1))=lower(mentioned) limit 1;
  if assignee is null then return null; end if;
  task_title := trim(regexp_replace(regexp_replace(m.body,'@[A-Za-z0-9_]+','','g'),'(complete|finish|do|send|update|fix|create|prepare|make|write|review)',' ','gi'));
  if length(task_title)<2 then task_title := 'New Task'; end if;
  insert into public.task_suggestions(workspace_id,message_id,assignee_id,title)
  values(m.workspace_id,m.id,assignee,initcap(task_title)) on conflict(message_id) do update set title=excluded.title
  returning id into suggestion_id;
  return suggestion_id;
end $$;

create or replace function public.confirm_task_suggestion(p_suggestion_id bigint) returns bigint
language plpgsql security definer set search_path=public as $$
declare s public.task_suggestions; m public.messages; t_id bigint;
begin
  select * into s from public.task_suggestions where id=p_suggestion_id and public.is_workspace_member(workspace_id) for update;
  if not found then raise exception 'Suggestion not found'; end if;
  if s.confirmed_task_id is not null then return s.confirmed_task_id; end if;
  select * into m from public.messages where id=s.message_id;
  insert into public.tasks(workspace_id,channel_id,source_message_id,creator_profile_id,assignee_id,title,deadline,priority,source_type,origin_text,client_mutation_id)
  values(s.workspace_id,m.channel_id,m.id,public.current_profile_id(),s.assignee_id,s.title,s.deadline,s.priority,'message',m.body,gen_random_uuid()) returning id into t_id;
  update public.task_suggestions set status='confirmed',confirmed_task_id=t_id,updated_at=now() where id=s.id;
  return t_id;
end $$;

