create or replace function public.taskly_register_device_token_v40(
  p_token text,
  p_platform text,
  p_device_id text
) returns void
language plpgsql security definer set search_path=public as $$
declare v_profile bigint := public.current_profile_id();
begin
  if v_profile is null then raise exception 'Not authenticated'; end if;
  if p_platform not in ('android','ios','web') then raise exception 'Invalid platform'; end if;
  if length(trim(p_token)) < 20 or length(trim(p_device_id)) < 8 then raise exception 'Invalid device registration'; end if;

  delete from public.device_tokens
   where token=trim(p_token) and profile_id<>v_profile;

  insert into public.device_tokens(profile_id,platform,token,device_id,is_enabled,last_seen_at,updated_at)
  values(v_profile,p_platform,trim(p_token),trim(p_device_id),true,now(),now())
  on conflict(token) do update set
    profile_id=excluded.profile_id,
    platform=excluded.platform,
    device_id=excluded.device_id,
    is_enabled=true,
    last_seen_at=now(),
    updated_at=now();
end $$;

grant execute on function public.taskly_register_device_token_v40(text,text,text) to authenticated;

create or replace function public.taskly_unregister_device_token_v40(p_token text)
returns void language sql security definer set search_path=public as $$
  delete from public.device_tokens
  where profile_id=public.current_profile_id() and token=p_token
$$;
grant execute on function public.taskly_unregister_device_token_v40(text) to authenticated;

