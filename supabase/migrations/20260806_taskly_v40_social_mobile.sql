);
alter table public.message_reactions enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='message_reactions' and policyname='message_reactions_member_v40') then
    create policy message_reactions_member_v40 on public.message_reactions for all
      using (exists (
        select 1 from public.messages m
        where m.id=message_id and public.is_workspace_member(m.workspace_id)
      ))
      with check (
        profile_id=public.current_profile_id() and exists (
          select 1 from public.messages m
          where m.id=message_id and public.is_workspace_member(m.workspace_id)
        )
      );
  end if;
end $$;

