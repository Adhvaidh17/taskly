-- Widen only the message-type check so new message cards remain valid.
do $$
declare constraint_name text;
begin
  for constraint_name in
    select con.conname
    from pg_constraint con
    where con.conrelid = 'public.messages'::regclass
      and con.contype = 'c'
      and pg_get_constraintdef(con.oid) ilike '%type%'
  loop
    execute format('alter table public.messages drop constraint if exists %I', constraint_name);
  end loop;
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.messages'::regclass
      and conname = 'messages_type_v40_check'
  ) then
    alter table public.messages add constraint messages_type_v40_check
      check (type in ('text','voice','system','file','image','contact'));
  end if;
end $$;

