-- Taskly Supabase/PostgreSQL schema
create extension if not exists pgcrypto;

create table public.profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null,
  email text not null,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.workspaces (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  owner_profile_id bigint references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.workspace_members (
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','admin','member','guest')),
  is_active boolean not null default true,
  joined_at timestamptz not null default now(),
  primary key (workspace_id, profile_id)
);
create index workspace_members_user_idx on public.workspace_members(user_id, is_active);

create table public.clients (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  name text not null,
  colour text not null default '#64748B',
  icon text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(workspace_id, name)
);

create table public.channels (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  client_id bigint references public.clients(id) on delete set null,
  name text not null,
  type text not null default 'team' check (type in ('team','project','direct')),
  icon text,
  is_archived boolean not null default false,
  created_by_profile_id bigint references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(workspace_id, name)
);

create table public.channel_members (
  channel_id bigint not null references public.channels(id) on delete cascade,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  last_read_at timestamptz,
  primary key(channel_id, profile_id)
);

create table public.messages (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  channel_id bigint not null references public.channels(id) on delete cascade,
  sender_profile_id bigint not null references public.profiles(id),
  body text not null,
  type text not null default 'text' check(type in ('text','voice','system')),
  client_mutation_id uuid unique,
  reply_to_message_id bigint references public.messages(id) on delete set null,
  edited_at timestamptz,
  deleted_at timestamptz,
  created_at timestamptz not null default now()
);
create index messages_channel_created_idx on public.messages(channel_id, created_at);

create table public.tasks (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  client_id bigint references public.clients(id) on delete set null,
  channel_id bigint references public.channels(id) on delete set null,
  source_message_id bigint references public.messages(id) on delete set null,
  creator_profile_id bigint not null references public.profiles(id),
  assignee_id bigint references public.profiles(id) on delete set null,
  title text not null,
  description text,
  status text not null default 'todo' check(status in ('todo','in-progress','done')),
  priority text not null default 'medium' check(priority in ('low','medium','high')),
  deadline timestamptz,
  position numeric(18,6) not null default 0,
  source_type text not null default 'manual' check(source_type in ('manual','message','voice')),
  origin_text text,
  reminder_enabled boolean not null default false,
  version integer not null default 1,
  client_mutation_id uuid unique,
  completed_at timestamptz,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index tasks_workspace_status_idx on public.tasks(workspace_id,status,deadline);
create index tasks_assignee_idx on public.tasks(assignee_id,status);

create table public.subtasks (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  title text not null,
  is_done boolean not null default false,
  position integer not null default 0,
  version integer not null default 1,
  client_mutation_id uuid unique,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.task_comments (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  profile_id bigint not null references public.profiles(id),
